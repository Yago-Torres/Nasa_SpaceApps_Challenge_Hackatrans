"""Complete, verifiable case report: snapshot assembly helpers and Markdown/HTML renderers (ABB-26).

This module is pure (no database, no network). ``api/reports.py`` reads the case and passes plain data
here; the result is a JSON-safe *snapshot* plus two renderings of that same snapshot, so the Markdown,
the HTML and the JSON download can never disagree.

Design rules (see ``docs/science/CASE_REPORT.md``):

- Nothing is invented. Every number, DOI and identifier comes from a stored record; the renderers only
  lay it out. Sections with no stored data say so explicitly.
- Exports are *shareable* documents: exact coordinates, the grid-cell centre, free-text incident notes,
  e-mail addresses, member names and comment text are never part of a snapshot.
- Evidence classes are never merged: observed data, farmer-reported records, reviewed literature,
  bibliographic metadata, hypotheses, rule-based model scenarios and human conclusions keep their label.
"""
