"""Rotation comparison engine with farmer constraints (ABB-17) and the illustrative demo.

Method (docs/science/ROTATIONS.md):
- The current rotation is derived from the farmer's crop history and is always listed first.
- Alternatives are generated by transparent rules that only use the crop catalogue
  (botanical family, legume status) and what the farmer declared: local calendar month
  windows, excluded crops, market access, water regime and crop history.
- Calendar compatibility between consecutive crops is checked on the declared windows
  (one main crop per year). Impossible sequences are rejected, never repaired.
- The comparison is descriptive (families, legumes, calendar months with a crop, fallow
  gaps, market status, constraint checks). No yield, water, income or benefit figure and no
  score is produced; ``verified_impact`` is always ``None``.

Everything here is deterministic: the same request returns the same response.
"""
