def _horizon(request: RotationCompareRequest) -> tuple[int, list[str]]:
    if request.horizon_years is not None:
        return request.horizon_years, []
    declared = request.profile.constraints.planning_horizon_years if request.profile.constraints else None
    if declared is None:
        return DEFAULT_HORIZON_YEARS, [f'No planning horizon declared; {DEFAULT_HORIZON_YEARS} years are laid out.']
    if declared < 2:
        return 2, ['Declared planning horizon is 1 year; 2 years are laid out, the minimum to show a sequence.']
    return declared, []


def compare_rotations(request: RotationCompareRequest) -> RotationComparison:
    profile = request.profile
    horizon, explanation = _horizon(request)
    assessment = assess_profile(profile)
    base = dict(horizon_years=horizon, profile_readiness=assessment.rotation_input_status,
                profile_issues=assessment.issues, limitations=list(LIMITATIONS))
    if assessment.rotation_input_status == 'BLOCKED_BY_ERRORS':
        errors = [f'{i.path}: {i.message}' for i in assessment.issues if i.severity == 'ERROR']
        return RotationComparison(status='BLOCKED_BY_PROFILE_ERRORS', strategies=[], candidate_screening=[],
                                  incompatible_transitions=[], generation=None,
                                  explanation=['The farm profile has inconsistencies that must be fixed before '
                                               'rotations are compared.', *errors], **base)
    reg = _Registry(profile)
    screening = _screen(reg, profile)
    current = _derive_current(profile, reg)
    if current is None:
        return RotationComparison(
            status='INSUFFICIENT_INPUT', strategies=[], candidate_screening=screening, incompatible_transitions=[],
            generation=None, explanation=[*explanation, 'At least two years with a main crop are needed in crop_history '
                                          'to identify the current rotation; no strategy is compared without it.'],
            **base)

    current_crops = _crops(current.cycle)
    offset = len(current.recorded) % len(current.cycle)
    current_years = [current.cycle[(offset + k) % len(current.cycle)] for k in range(horizon)]
    start_year = current.years[-1] + 1
    current_strategy = _build_strategy(
        sid='current', name='Current rotation (recorded)', kind='CURRENT',
        rule='Derived from crop_history; projected unchanged over the horizon.', cycle=current.cycle,
        years=current_years, start_year=start_year, entry=None, reg=reg, profile=profile, ref=None,
        current_crops=current_crops,
        assumptions=[*current.notes, 'The farmer continues the recorded rotation over the horizon.'])
    ref = current_strategy.comparison

    # ELIGIBLE implies a catalogue entry, so the crop code is the registry key.
    eligible = [reg.crops[s.crop.crop_code] for s in screening if s.status == 'ELIGIBLE']
    candidates, lengths = _generate(eligible, reg, current, horizon)
    last_crop, last_offset = _last_recorded_crop(current)
    strategies = [current_strategy]
    chosen: set[tuple[str, ...]] = set()
    for kind, name, rule in ARCHETYPES:
        ranked = sorted((c for c in candidates if c.keys not in chosen), key=lambda c: _sort_key(kind, c, len(current.cycle)))
        if not ranked:
            continue
        pick = ranked[0]
        chosen.add(pick.keys)
        seq, entry = _align_to_history(pick.seq, last_crop, last_offset)
        cycle = [(c,) for c in seq]
        strategies.append(_build_strategy(
            sid=f'alt-{len(strategies)}-{kind.lower().replace("_", "-")}', name=name, kind=kind, rule=rule,
            cycle=cycle, years=[cycle[k % len(cycle)] for k in range(horizon)], start_year=start_year,
            entry=entry, reg=reg, profile=profile, ref=ref, current_crops=current_crops,
            assumptions=['Generated from farmer-declared windows, markets and exclusions; one main crop per year.',
                         'The cycle repeats unchanged over the horizon.',
                         'Crops already grown on the farm are assumed manageable with current equipment.']))

    alternatives = len(strategies) - 1
    pairs = sorted(((a, b) for a in eligible for b in eligible if a.key != b.key), key=lambda p: (p[0].key, p[1].key))
    incompatible = [t for t in (check_transition(a, b) for a, b in pairs) if t.status == 'INCOMPATIBLE']
    if alternatives < 2:
        explanation.extend(_why_fewer(profile, eligible, candidates, alternatives))
    return RotationComparison(
        status='COMPARED' if alternatives >= 2 else 'FEWER_ALTERNATIVES', strategies=strategies,
        explanation=explanation, candidate_screening=screening, incompatible_transitions=incompatible,
        generation=GenerationSummary(eligible_crops=[c.label for c in eligible], cycle_lengths_considered=lengths,
                                     feasible_sequences=len(candidates), rules=list(RULES)),
        **base)


def _why_fewer(profile: FarmProfile, eligible: list[_Crop], candidates: list[_Candidate], found: int) -> list[str]:
    reasons = [f'Only {found} alternative(s) could be generated; at least 2 are expected.']
    if not profile.local_calendar:
        reasons.append('No local_calendar declared: candidate crops cannot be calendar-checked, and the catalogue '
                       'deliberately provides no calendar defaults.')
    if len(eligible) < 2:
        reasons.append(f'{len(eligible)} crop(s) passed screening; a rotation needs at least two crops of different '
                       'families (see candidate_screening for excluded and not-evaluable crops).')
    elif len({c.family for c in eligible}) < 2:
        reasons.append(f'All eligible crops belong to {eligible[0].family}; alternatives may not repeat a family in '
                       'consecutive years.')
    elif not candidates:
        reasons.append('No sequence of eligible crops avoids impossible calendar transitions and consecutive '
                       'same-family years (see incompatible_transitions).')
    else:
        reasons.append(f'Only {len(candidates)} distinct feasible sequence(s) differ from the current rotation.')
    return reasons


def to_shared_rotation(strategy: RotationStrategy, *, rotation_id: UUID, case_id: UUID) -> Rotation:
    """Map a strategy onto the shared ABB-02 ``Rotation`` contract (e.g. for later persistence)."""
    return Rotation(id=rotation_id, case_id=case_id, source_kind=SourceKind.MODEL_SCENARIO, name=strategy.name,
                    years=strategy.years, is_current=strategy.is_current, assumptions=strategy.assumptions,
                    constraints=[f'{c.constraint}: {c.status}' for c in strategy.constraint_checks],
                    limitations=strategy.limitations)
