@dataclass(frozen=True)
class _Crop:
    key: str
    code: str | None
    label: str
    family: str | None
    is_legume: bool | None
    window: CalendarWindow | None

    @property
    def has_full_window(self) -> bool:
        return self.window is not None and self.window.harvest_start_month is not None

    def ref(self) -> CropRef:
        return CropRef(crop_code=self.code, crop_label=self.label,
                       botanical_family=self.family, is_legume=self.is_legume)


Slot = tuple[_Crop, ...]  # empty = fallow year, one crop = normal year, several = double cropping


def _norm(text: str) -> str:
    return ' '.join(text.casefold().split())


def _key_for(code: str | None, label: str) -> tuple[str, str | None]:
    if code and code in ENTRIES:
        return code, code
    entry = resolve_crop(label)
    if entry is not None:
        return entry.code, entry.code
    return f'label:{_norm(label)}', None


class _Registry:
    """Resolves every crop named in the profile once, so all rules see the same identity."""

    def __init__(self, profile: FarmProfile):
        self.crops: dict[str, _Crop] = {}
        self.windows: dict[str, CalendarWindow] = {}
        self.declared_in: dict[str, set[str]] = {}
        for window in profile.local_calendar:
            key, _ = _key_for(window.crop_code, window.crop_label)
            self.windows.setdefault(key, window)  # duplicates are flagged by ABB-11; first one wins
        for window in profile.local_calendar:
            self._add(window.crop_code, window.crop_label, 'LOCAL_CALENDAR')
        for season in profile.crop_history:
            if season.role == SeasonRole.MAIN_CROP:
                self._add(season.crop_code, season.crop_label, 'CROP_HISTORY')
        c = profile.constraints
        self.market: dict[str, str] = {}
        self.excluded: set[str] = set()
        if c is not None:
            for m in c.market_access:
                key = self._add(m.crop_code, m.crop_label, 'MARKET_ACCESS')
                self.market.setdefault(key, m.status)
            for name in c.excluded_crops:
                self.excluded.add(_key_for(None, name)[0])
        self.history_regimes: dict[str, set[WaterRegime]] = {}
        for season in profile.crop_history:
            if season.role == SeasonRole.MAIN_CROP:
                key, _ = _key_for(season.crop_code, season.crop_label)
                self.history_regimes.setdefault(key, set()).add(season.water_regime)

    def _add(self, code: str | None, label: str, origin: str) -> str:
        key, resolved = _key_for(code, label)
        self.declared_in.setdefault(key, set()).add(origin)
        if key not in self.crops:
            entry = ENTRIES.get(resolved) if resolved else None
            window = self.windows.get(key)
            shown = window.crop_label if window else label
            self.crops[key] = _Crop(key=key, code=resolved, label=shown,
                                    family=entry.botanical_family if entry else None,
                                    is_legume=entry.is_legume if entry else None, window=window)
        return key

    def crop(self, code: str | None, label: str) -> _Crop:
        return self.crops[_key_for(code, label)[0]]

    def market_status(self, key: str) -> str:
        return self.market.get(key, 'NOT_DECLARED')


# ---------------------------------------------------------------- calendar arithmetic (absolute months)

def _latest_at_or_before(absolute: int, month: int) -> int:
    """Latest absolute month index <= ``absolute`` whose calendar month is ``month`` (1-12)."""
    return absolute - ((absolute % 12) - (month - 1)) % 12


def _slot_months(window: CalendarWindow, year: int) -> tuple[int, int, int, int]:
    """(sow_start, sow_end, harvest_start, harvest_end) as absolute months for a crop harvested in ``year``.

    The harvest window starts in ``year`` (it may end in the next year if it wraps the year end). Sowing
    is the latest occurrence of the declared sowing window at or before the earliest harvest month.
    """
    h_start = 12 * year + window.harvest_start_month - 1
    h_end = h_start + (window.harvest_end_month - window.harvest_start_month) % 12
    s_end = _latest_at_or_before(h_start, window.sowing_end_month)
    s_start = _latest_at_or_before(s_end, window.sowing_start_month)
    return s_start, s_end, h_start, h_end


def check_transition(previous: _Crop, following: _Crop, year_offset: int = 1) -> TransitionCheck:
    """Calendar check between a crop and the next one, ``year_offset`` slot years later."""
    same_family = (previous.family == following.family
                   if previous.family is not None and following.family is not None else None)
    base = {'from_crop': previous.label, 'to_crop': following.label, 'same_family': same_family}
    missing = [c.label for c in (previous, following) if not c.has_full_window]
    if missing:
        return TransitionCheck(status='NOT_EVALUABLE', **base,
                               message=f'No complete sowing/harvest window declared for {", ".join(missing)}; '
                                       'the sequence cannot be calendar-checked.')
    _, _, a_hs, a_he = _slot_months(previous.window, 0)
    b_ss, b_se, _, _ = _slot_months(following.window, year_offset)
    if b_se < a_hs:
        return TransitionCheck(status='INCOMPATIBLE', **base,
                               message=f'{following.label} must be sown by month {following.window.sowing_end_month}, '
                                       f'before {previous.label} can be harvested (from month '
                                       f'{previous.window.harvest_start_month}).')
    gap = MonthRange(min=max(0, b_ss - a_he - 1), max=max(0, b_se - a_hs - 1))
    if b_ss > a_he:
        return TransitionCheck(status='COMPATIBLE', fallow_gap=gap, **base,
                               message=f'{previous.label} harvest window ends before the {following.label} '
                                       'sowing window starts.')
    return TransitionCheck(status='TIGHT', fallow_gap=gap, **base,
                           message=f'{previous.label} harvest and {following.label} sowing windows touch or '
                                   'overlap; feasible only with an early harvest and a late sowing.')


def _cycle_transitions(cycle: list[Slot]) -> list[TransitionCheck]:
    """Transitions between consecutive crop years, including the return to the start of the cycle."""
    length = len(cycle)
    crop_years = [i for i, slot in enumerate(cycle) if slot]
    out = []
    for n, i in enumerate(crop_years):
        j = crop_years[(n + 1) % len(crop_years)]
        offset = j - i if j > i else j + length - i
        a, b = cycle[i], cycle[j]
        if len(a) > 1 or len(b) > 1:
            out.append(TransitionCheck(
                from_crop=' + '.join(c.label for c in a), to_crop=' + '.join(c.label for c in b),
                status='NOT_EVALUABLE', message='More than one main crop in a year (double cropping) is not modelled.'))
            continue
        out.append(check_transition(a[0], b[0], offset))
    return out


def _months_with_crop(cycle: list[Slot]) -> MonthRange | None:
    if any(len(slot) > 1 or (slot and not slot[0].has_full_window) for slot in cycle):
        return None
    period = 12 * len(cycle)
    certain: set[int] = set()
    possible: set[int] = set()
    for year, slot in enumerate(cycle):
        if not slot:
            continue
        s_start, s_end, h_start, h_end = _slot_months(slot[0].window, year)
        certain.update(m % period for m in range(s_end, h_start + 1))
        possible.update(m % period for m in range(s_start, h_end + 1))
    years = len(cycle)
    return MonthRange(min=round(len(certain) / years, 1), max=round(len(possible) / years, 1),
                      unit='months per year')


def _crops(cycle: list[Slot]) -> list[_Crop]:
    return [c for slot in cycle for c in slot]


def _consecutive_same_family(transitions: list[TransitionCheck]) -> int | None:
    if any(t.same_family is None for t in transitions):
        known = sum(1 for t in transitions if t.same_family)
        return known or None
    return sum(1 for t in transitions if t.same_family)


# ---------------------------------------------------------------- current rotation

@dataclass
class _Current:
    recorded: list[Slot]
    cycle: list[Slot]
    years: list[int]
    notes: list[str]


def _derive_current(profile: FarmProfile, reg: _Registry) -> _Current | None:
    by_year: dict[int, list] = {}
    fallow_years: set[int] = set()
    for season in profile.crop_history:
        if season.role == SeasonRole.MAIN_CROP:
            by_year.setdefault(season.season_year, []).append(season)
        elif season.role == SeasonRole.FALLOW:
            fallow_years.add(season.season_year)
    if len(by_year) < 2:
        return None
    notes = []
    first, last = min(by_year), max(by_year.keys() | fallow_years)
    years = list(range(first, last + 1))
    recorded: list[Slot] = []
    missing = []
    for year in years:
        seasons = sorted(by_year.get(year, []), key=lambda s: (s.sowing_date is None, s.sowing_date, s.crop_label))
        if seasons:
            recorded.append(tuple(reg.crop(s.crop_code, s.crop_label) for s in seasons))
        else:
            recorded.append(())
            if year not in fallow_years:
                missing.append(year)
    if missing:
        notes.append(f'No season recorded for {", ".join(map(str, missing))}; treated as fallow.')
    if any(len(slot) > 1 for slot in recorded):
        notes.append('Some years record more than one main crop (double cropping); those years are not calendar-checked.')
    keys = [tuple(c.key for c in slot) for slot in recorded]
    period = next(p for p in range(1, len(keys) + 1)
                  if all(keys[i] == keys[i + p] for i in range(len(keys) - p)))
    if period < len(keys):
        notes.append(f'The recorded sequence repeats every {period} year(s); that repeating cycle is projected.')
    else:
        notes.append('No repeating period found in the recorded years; the whole recorded sequence is '
                     'assumed to repeat.')
    return _Current(recorded=recorded, cycle=recorded[:period], years=years, notes=notes)


# ---------------------------------------------------------------- candidate screening

def _screen(reg: _Registry, profile: FarmProfile) -> list[CandidateScreening]:
    rainfed = profile.constraints is not None and profile.constraints.water_regime == WaterRegime.RAINFED
    out = []
    for key in sorted(reg.crops):
        crop = reg.crops[key]
        reasons: list[ScreeningReason] = []
        excluded = False
        if key in reg.excluded:
            excluded = True
            reasons.append(ScreeningReason(code='EXCLUDED_BY_FARMER', message=f'{crop.label} is in the excluded crops.'))
        if reg.market_status(key) == 'NO_MARKET':
            excluded = True
            reasons.append(ScreeningReason(code='NO_MARKET', message=f'The farmer declared no market for {crop.label}.'))
        regimes = reg.history_regimes.get(key, set())
        irrigated = {WaterRegime.IRRIGATED, WaterRegime.SUPPLEMENTAL_IRRIGATION}
        if rainfed and regimes and regimes <= irrigated:
            excluded = True
            reasons.append(ScreeningReason(
                code='IRRIGATED_ONLY_ON_RAINFED_FARM',
                message=f'{crop.label} was only grown with irrigation on this farm, which is now declared rainfed.'))
        if crop.family is None:
            reasons.append(ScreeningReason(code='CROP_NOT_IN_CATALOGUE',
                                           message=f'{crop.label} is not in the crop catalogue; its family is unknown.'))
        if crop.window is None:
            reasons.append(ScreeningReason(code='CALENDAR_NOT_DECLARED',
                                           message=f'No sowing/harvest window declared for {crop.label}; '
                                                   'it cannot be calendar-checked.'))
        elif not crop.has_full_window:
            reasons.append(ScreeningReason(code='HARVEST_WINDOW_NOT_DECLARED',
                                           message=f'No harvest window declared for {crop.label}.'))
        status = 'EXCLUDED' if excluded else ('NOT_EVALUABLE' if reasons else 'ELIGIBLE')
        out.append(CandidateScreening(
            crop=crop.ref(), status=status, reasons=reasons,
            declared_in=sorted(reg.declared_in.get(key, set())), market_status=reg.market_status(key),
            grown_on_farm='CROP_HISTORY' in reg.declared_in.get(key, set())))
    return out


# ---------------------------------------------------------------- alternative generation

@dataclass(frozen=True)
class _Candidate:
    seq: tuple[_Crop, ...]
    keys: tuple[str, ...]
    has_legume: bool
    n_families: int
    n_tight: int
    n_new: int
    n_shared: int
    n_market_unconfirmed: int
    months_min: float
    longest_gap_max: float


def _canonical(keys: tuple[str, ...]) -> tuple[str, ...]:
    return min(keys[i:] + keys[:i] for i in range(len(keys)))


def _generate(eligible: list[_Crop], reg: _Registry, current: _Current, horizon: int) -> tuple[list[_Candidate], list[int]]:
    current_keys = {c.key for c in _crops(current.cycle)}
    current_canon = (_canonical(tuple(slot[0].key for slot in current.cycle))
                     if all(len(slot) == 1 for slot in current.cycle) else None)
    pair: dict[tuple[str, str], TransitionCheck] = {
        (a.key, b.key): check_transition(a, b) for a in eligible for b in eligible}
    lengths = list(range(2, min(MAX_ALTERNATIVE_CYCLE_YEARS, horizon) + 1))
    history = {k for k, origins in reg.declared_in.items() if 'CROP_HISTORY' in origins}
    seen: set[tuple[str, ...]] = set()
    found = []
    for length in lengths:
        for seq in product(eligible, repeat=length):
            keys = tuple(c.key for c in seq)
            if keys != _canonical(keys) or keys in seen or keys == current_canon:
                continue
            checks = [pair[(seq[i].key, seq[(i + 1) % length].key)] for i in range(length)]
            if any(t.status == 'INCOMPATIBLE' or t.same_family for t in checks):
                continue
            seen.add(keys)
            cycle = [(c,) for c in seq]
            months = _months_with_crop(cycle)
            distinct = {c.key for c in seq}
            found.append(_Candidate(
                seq=seq, keys=keys, has_legume=any(c.is_legume for c in seq),
                n_families=len({c.family for c in seq}), n_tight=sum(t.status == 'TIGHT' for t in checks),
                n_new=len(distinct - history),
                n_shared=len(distinct & current_keys),
                n_market_unconfirmed=sum(reg.market_status(k) not in {'SELLABLE', 'CONTRACTED'} for k in distinct),
                months_min=months.min, longest_gap_max=max(t.fallow_gap.max for t in checks)))
    return found, lengths


ARCHETYPES: list[tuple[StrategyKind, str, str]] = [
    ('MINIMAL_CHANGE', 'Closest to the current rotation',
     'Keeps the most current crops, then adds the fewest crops new to the farm, then the cycle length '
     'closest to the current one, then the fewest TIGHT transitions and unconfirmed markets.'),
    ('FAMILY_DIVERSIFICATION', 'Diversified families (legume where eligible)',
     'Includes a legume if any is eligible, then the most botanical families, then the fewest TIGHT '
     'transitions, unconfirmed markets and crops new to the farm.'),
    ('CALENDAR_COVER', 'Most calendar months with a crop',
     'Most months per year with a crop in the field by the declared windows, then the shortest longest '
     'fallow gap, then the fewest TIGHT transitions, unconfirmed markets and new crops.'),
]


def _sort_key(kind: StrategyKind, c: _Candidate, current_len: int):
    tail = (len(c.seq), c.keys)
    if kind == 'MINIMAL_CHANGE':
        return (-c.n_shared, c.n_new, abs(len(c.seq) - current_len), c.n_tight, c.n_market_unconfirmed) + tail
    if kind == 'FAMILY_DIVERSIFICATION':
        return (not c.has_legume, -c.n_families, c.n_tight, c.n_market_unconfirmed, c.n_new) + tail
    return (-c.months_min, c.longest_gap_max, c.n_tight, c.n_market_unconfirmed, c.n_new) + tail


_ENTRY_ORDER = {'COMPATIBLE': 0, 'TIGHT': 1, 'NOT_EVALUABLE': 2, 'INCOMPATIBLE': 3}


def _last_recorded_crop(current: _Current) -> tuple[_Crop | None, int]:
    """Last recorded single main crop and how many slot years before the first projected year it was harvested."""
    for index in range(len(current.recorded) - 1, -1, -1):
        slot = current.recorded[index]
        if slot:
            return (slot[0] if len(slot) == 1 else None), len(current.recorded) - index
    return None, 1


def _align_to_history(seq: tuple[_Crop, ...], last: _Crop | None,
                      offset: int) -> tuple[tuple[_Crop, ...], TransitionCheck | None]:
    """Rotate the cycle so its first year follows the last recorded crop as well as the calendar allows."""
    if last is None:
        return seq, None
    options = []
    for r in range(len(seq)):
        rotated = seq[r:] + seq[:r]
        entry = check_transition(last, rotated[0], offset)
        options.append(((_ENTRY_ORDER[entry.status], bool(entry.same_family), r), rotated, entry))
    _, rotated, entry = min(options, key=lambda o: o[0])
    return rotated, entry


