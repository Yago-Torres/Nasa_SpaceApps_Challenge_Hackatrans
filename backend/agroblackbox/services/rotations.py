def _constraint_checks(cycle: list[Slot], transitions: list[TransitionCheck], reg: _Registry,
                       profile: FarmProfile) -> list[ConstraintCheck]:
    crops = _crops(cycle)

    def labels(items: list[_Crop]) -> str:
        return ', '.join(sorted({x.label for x in items}))

    c = profile.constraints
    checks = []

    if c is None:
        checks.append(ConstraintCheck(constraint='EXCLUDED_CROPS', status='NOT_EVALUABLE', detail='No constraints declared.'))
    else:
        hit = [x for x in crops if x.key in reg.excluded]
        checks.append(ConstraintCheck(
            constraint='EXCLUDED_CROPS', status='VIOLATED' if hit else 'SATISFIED',
            detail=f'Includes excluded crop(s): {labels(hit)}.' if hit else 'No excluded crop is used.'))

    if c is None or not c.market_access:
        checks.append(ConstraintCheck(constraint='MARKET_ACCESS', status='NOT_EVALUABLE',
                                      detail='No market access declared.'))
    else:
        no_market = [x for x in crops if reg.market_status(x.key) == 'NO_MARKET']
        unconfirmed = [x for x in crops if reg.market_status(x.key) in {'UNKNOWN', 'NOT_DECLARED'}]
        if no_market:
            checks.append(ConstraintCheck(constraint='MARKET_ACCESS', status='VIOLATED',
                                          detail=f'No market declared for {labels(no_market)}.'))
        elif unconfirmed:
            checks.append(ConstraintCheck(constraint='MARKET_ACCESS', status='REVIEW_REQUIRED',
                                          detail=f'Market not confirmed for {labels(unconfirmed)}.'))
        else:
            checks.append(ConstraintCheck(constraint='MARKET_ACCESS', status='SATISFIED',
                                          detail='Every crop has a declared SELLABLE or CONTRACTED market.'))

    statuses = {t.status for t in transitions}
    if 'INCOMPATIBLE' in statuses:
        cal = ('VIOLATED', 'At least one consecutive pair is impossible with the declared windows.')
    elif 'NOT_EVALUABLE' in statuses:
        cal = ('NOT_EVALUABLE', 'At least one consecutive pair cannot be checked (missing window or double cropping).')
    elif 'TIGHT' in statuses:
        cal = ('REVIEW_REQUIRED', 'At least one harvest and next sowing window touch or overlap.')
    else:
        cal = ('SATISFIED', 'Every harvest window ends before the next sowing window starts.')
    checks.append(ConstraintCheck(constraint='LOCAL_CALENDAR', status=cal[0], detail=cal[1]))

    regime = c.water_regime if c is not None else WaterRegime.UNKNOWN
    irrigated = {WaterRegime.IRRIGATED, WaterRegime.SUPPLEMENTAL_IRRIGATION}
    if regime == WaterRegime.UNKNOWN:
        checks.append(ConstraintCheck(constraint='WATER_REGIME', status='NOT_EVALUABLE',
                                      detail='Farm water regime unknown.'))
    elif regime == WaterRegime.RAINFED:
        irrigated_only = [x for x in crops if reg.history_regimes.get(x.key) and reg.history_regimes[x.key] <= irrigated]
        not_rainfed_before = [x for x in crops if WaterRegime.RAINFED not in reg.history_regimes.get(x.key, set())]
        if irrigated_only:
            checks.append(ConstraintCheck(
                constraint='WATER_REGIME', status='REVIEW_REQUIRED',
                detail=f'Farm declared rainfed but {labels(irrigated_only)} was only grown with irrigation here; '
                       'this assumes irrigation the farm does not declare.'))
        elif not_rainfed_before:
            checks.append(ConstraintCheck(
                constraint='WATER_REGIME', status='REVIEW_REQUIRED',
                detail=f'No rainfed record on this farm for {labels(not_rainfed_before)}; rainfed feasibility '
                       'is not evaluated (no crop water-demand data).'))
        else:
            checks.append(ConstraintCheck(constraint='WATER_REGIME', status='SATISFIED',
                                          detail='Every crop was previously grown rainfed on this farm (crop history).'))
    else:
        checks.append(ConstraintCheck(constraint='WATER_REGIME', status='NOT_EVALUABLE',
                                      detail='Irrigation demand is not compared with the declared allowance '
                                             '(no crop water-demand data or water model).'))

    same = _consecutive_same_family(transitions)
    if same:
        checks.append(ConstraintCheck(constraint='FAMILY_REPETITION', status='REVIEW_REQUIRED',
                                      detail=f'{same} consecutive pair(s) per cycle share a botanical family.'))
    elif same is None:
        checks.append(ConstraintCheck(constraint='FAMILY_REPETITION', status='NOT_EVALUABLE',
                                      detail='Family unknown for at least one crop.'))
    else:
        checks.append(ConstraintCheck(constraint='FAMILY_REPETITION', status='SATISFIED',
                                      detail='No botanical family is repeated in consecutive years.'))

    new = [x for x in crops if 'CROP_HISTORY' not in reg.declared_in.get(x.key, set())]
    has_equipment_info = c is not None and (c.available_equipment or c.equipment_limitations)
    if new and not has_equipment_info:
        checks.append(ConstraintCheck(constraint='EQUIPMENT', status='NOT_EVALUABLE',
                                      detail=f'No equipment declared; needs of {labels(new)} cannot be checked.'))
    elif new:
        checks.append(ConstraintCheck(constraint='EQUIPMENT', status='REVIEW_REQUIRED',
                                      detail=f'Not grown on this farm before: {labels(new)}; confirm the declared '
                                             'equipment can sow and harvest them.'))
    else:
        checks.append(ConstraintCheck(constraint='EQUIPMENT', status='SATISFIED',
                                      detail='Assumption: all crops were grown on this field before, so they are '
                                             'taken as manageable with the current equipment (not verified).'))
    checks.append(ConstraintCheck(constraint='SOIL', status='NOT_EVALUABLE',
                                  detail=f'{len(profile.soil)} soil observation(s) declared, but no reviewed '
                                         'crop–soil suitability parameters exist; soil is not evaluated.'))
    checks.append(ConstraintCheck(constraint='CLIMATE', status='NOT_EVALUABLE',
                                  detail='Only the farmer-declared windows reflect local climate; no climate '
                                         'suitability model is applied.'))
    return checks


def _screening_result(checks: list[ConstraintCheck]) -> str:
    hard = {'EXCLUDED_CROPS', 'MARKET_ACCESS', 'LOCAL_CALENDAR'}
    if any(c.constraint in hard and c.status == 'VIOLATED' for c in checks):
        return 'CONFLICTS_WITH_DECLARED_CONSTRAINTS'
    if any(c.constraint == 'LOCAL_CALENDAR' and c.status == 'NOT_EVALUABLE' for c in checks):
        return 'NOT_FULLY_EVALUABLE'
    return 'PASSES_DECLARED_CONSTRAINTS'


def _comparison(cycle: list[Slot], transitions: list[TransitionCheck], reg: _Registry) -> DescriptiveComparison:
    crops = _crops(cycle)
    distinct = {c.key: c for c in crops}
    families = sorted({c.family for c in crops if c.family})
    not_evaluable = []
    if any(c.family is None for c in crops):
        not_evaluable.append('Family unknown for crops outside the catalogue; family counts cover catalogued crops only.')
    months = _months_with_crop(cycle)
    if months is None:
        not_evaluable.append('Months with a crop not computed: a crop lacks a complete declared window or a '
                             'year has more than one main crop.')
    gaps = [t.fallow_gap for t in transitions if t.fallow_gap is not None]
    longest = None
    if gaps and len(gaps) == len(transitions):
        longest = max(gaps, key=lambda g: (g.max, g.min))
    elif transitions:
        not_evaluable.append('Fallow gaps not computed for every transition (missing window, double cropping '
                             'or impossible sequence).')
    return DescriptiveComparison(
        cycle_years=len(cycle), distinct_crops=len(distinct), distinct_families=len(families), families=families,
        includes_legume=any(c.is_legume for c in crops),
        legume_years_per_cycle=sum(1 for slot in cycle if any(c.is_legume for c in slot)),
        consecutive_same_family=_consecutive_same_family(transitions), months_with_crop=months,
        longest_fallow_gap=longest,
        crops_new_to_farm=sorted(c.label for c in distinct.values()
                                 if 'CROP_HISTORY' not in reg.declared_in.get(c.key, set())),
        market_status=[MarketStatusItem(crop_label=c.label, status=reg.market_status(k))
                       for k, c in sorted(distinct.items())],
        not_evaluable=not_evaluable)


def _relation(value, reference) -> str:
    if value is None or reference is None:
        return 'NOT_EVALUABLE'
    return 'MORE' if value > reference else 'LESS' if value < reference else 'SAME'


def _priority_notes(profile: FarmProfile, comp: DescriptiveComparison,
                    ref: DescriptiveComparison | None) -> list[PriorityNote]:
    notes = []
    for p in sorted(profile.priorities, key=lambda p: (p.rank, p.criterion.value)):
        crit = p.criterion
        if crit == PriorityCriterion.SOIL_COVER:
            value = comp.months_with_crop.min if comp.months_with_crop else None
            basis = 'Months per year with a crop in the field by the declared windows (calendar-based potential cover).'
            ref_value = ref.months_with_crop.min if ref and ref.months_with_crop else None
        elif crit == PriorityCriterion.CROP_DIVERSITY:
            value, ref_value = comp.distinct_families, ref.distinct_families if ref else None
            basis = 'Number of botanical families in the cycle.'
        else:
            value = ref_value = None
            basis = {
                PriorityCriterion.WATER_USE: 'Not evaluated: no crop water-demand data or water model.',
                PriorityCriterion.INCOME_STABILITY: 'Not evaluated: no prices or yields. See market_status per crop.',
                PriorityCriterion.WORKLOAD: 'Not evaluated: no labour data. See crops_new_to_farm.',
                PriorityCriterion.INPUT_COSTS: 'Not evaluated: no cost data.',
                PriorityCriterion.RISK_REDUCTION: 'Not evaluated: no risk model. See families and fallow gaps.',
            }.get(crit, 'Not evaluated: free-text priority.')
        relation = 'REFERENCE' if ref is None else _relation(value, ref_value)
        if ref is None and value is None and crit in {PriorityCriterion.SOIL_COVER, PriorityCriterion.CROP_DIVERSITY}:
            relation = 'NOT_EVALUABLE'
        notes.append(PriorityNote(criterion=crit, rank=p.rank, relation_to_current=relation, basis=basis))
    return notes


def _narrative(comp: DescriptiveComparison, ref: DescriptiveComparison | None, checks: list[ConstraintCheck],
               transitions: list[TransitionCheck], cycle: list[Slot], reg: _Registry,
               dropped: list[_Crop]) -> tuple[list[str], list[str], list[str], list[EvidenceRef]]:
    benefits, risks, review, evidence = [], [], [], []
    if ref is not None:
        if comp.includes_legume and not ref.includes_legume:
            benefits.append('Introduces a legume (Fabaceae). Legumes can add biologically fixed nitrogen to the '
                            'system; the amount is not estimated and requires local agronomic review.')
            evidence.append(EVIDENCE['legume'])
        if comp.distinct_families > ref.distinct_families:
            benefits.append(f'{comp.distinct_families} botanical families instead of {ref.distinct_families}. '
                            'Diversification can interrupt some family-specific pest, disease and weed cycles; '
                            'not quantified, requires review.')
            evidence.append(EVIDENCE['diversity'])
        if (comp.consecutive_same_family is not None and ref.consecutive_same_family
                and comp.consecutive_same_family < ref.consecutive_same_family):
            benefits.append('Fewer consecutive years with the same botanical family than the current rotation; '
                            'requires review.')
        if comp.months_with_crop and ref.months_with_crop:
            if comp.months_with_crop.min > ref.months_with_crop.min:
                benefits.append('More months per year with a crop in the field by the declared windows (potential '
                                'soil cover, not measured); requires review.')
            elif comp.months_with_crop.min < ref.months_with_crop.min:
                risks.append('Fewer months per year with a crop in the field by the declared windows than the '
                             'current rotation (more potential bare soil unless residues or a cover crop are kept).')
        for crop in dropped:
            if reg.market_status(crop.key) == 'CONTRACTED':
                risks.append(f'Drops {crop.label}, which has a CONTRACTED market.')
    elif comp.includes_legume:
        evidence.append(EVIDENCE['legume'])
    if comp.consecutive_same_family:
        risks.append('The same botanical family follows itself in consecutive years; family-specific pests, '
                     'diseases and weeds may carry over (not quantified).')
    for t in transitions:
        if t.status == 'TIGHT':
            risks.append(f'{t.from_crop} → {t.to_crop}: harvest and sowing windows touch or overlap; a late harvest '
                         'or wet weather could prevent timely sowing.')
        elif t.status == 'INCOMPATIBLE':
            risks.append(f'{t.from_crop} → {t.to_crop}: impossible with the declared windows ({t.message})')
    if comp.longest_fallow_gap and comp.longest_fallow_gap.max >= 6:
        risks.append(f'Up to {comp.longest_fallow_gap.max:g} months between a harvest and the next sowing '
                     '(potential bare soil unless residues or a cover crop are kept).')
    for new in comp.crops_new_to_farm:
        risks.append(f'No farm experience with {new}: management, equipment and market need checking.')
    for check in checks:
        if check.status in {'REVIEW_REQUIRED', 'NOT_EVALUABLE'} and check.constraint not in {'SOIL', 'CLIMATE'}:
            review.append(f'{check.constraint}: {check.detail}')
        elif check.status == 'VIOLATED':
            review.append(f'{check.constraint} conflict: {check.detail}')
    review.append('Soil and climate suitability of every crop (not evaluated by this tool).')
    review.append('Agronomist or extension-service review of the whole sequence before field use.')
    if any(slot and len(slot) == 1 and slot[0].is_legume for slot in cycle):
        review.append('Legume inoculation needs and herbicide carry-over from the previous crop.')
    return benefits, risks, review, evidence


def _build_strategy(*, sid: str, name: str, kind: StrategyKind, rule: str, cycle: list[Slot], years: list[Slot],
                    start_year: int | None, entry: TransitionCheck | None, reg: _Registry, profile: FarmProfile,
                    ref: DescriptiveComparison | None, current_crops: list[_Crop],
                    assumptions: list[str]) -> RotationStrategy:
    transitions = _cycle_transitions(cycle)
    checks = _constraint_checks(cycle, transitions, reg, profile)
    if entry is not None and entry.status == 'INCOMPATIBLE':
        checks = [ConstraintCheck(constraint='LOCAL_CALENDAR', status='VIOLATED',
                                  detail=f'Cannot start after the last recorded crop: {entry.message}')
                  if ch.constraint == 'LOCAL_CALENDAR' else ch for ch in checks]
    comp = _comparison(cycle, transitions, reg)
    in_cycle = {c.key for c in _crops(cycle)}
    dropped = sorted({c.key: c for c in current_crops if c.key not in in_cycle}.values(), key=lambda c: c.key)
    benefits, risks, review, evidence = _narrative(comp, ref, checks, transitions, cycle, reg, dropped)
    if entry is not None and entry.status == 'TIGHT':
        risks.append(f'Changeover from the last recorded crop ({entry.from_crop} → {entry.to_crop}) has touching '
                     'or overlapping windows.')
    return RotationStrategy(
        id=sid, name=name, strategy_kind=kind, is_current=kind == 'CURRENT',
        sequence_origin='FARMER_REPORTED' if kind == 'CURRENT' else 'RULE_GENERATED', selection_rule=rule,
        cycle=[[c.ref() for c in slot] for slot in cycle],
        years=[[c.label for c in slot] or [FALLOW_LABEL] for slot in years], start_season_year=start_year,
        transitions=transitions, entry_transition=entry, screening_result=_screening_result(checks),
        constraint_checks=checks, comparison=comp, priorities_addressed=_priority_notes(profile, comp, ref),
        possible_benefits=benefits, risks=risks, assumptions=assumptions, conditions_requiring_review=review,
        limitations=list(STRATEGY_LIMITATIONS), evidence_refs=evidence)


