    files = {**scene_files(L1), **scene_files(S1, nir_band='B8A', fmask=CLOUDY), **scene_files(L2)}
    fake = FakeNasa({'HLSL30': [granule_entry(L1), granule_entry(L2, cloud=100)],
                     'HLSS30': [granule_entry(S1)]}, files)
    series = await run(fake)
    by_id = {s.granule_id: s for s in series.scenes}
    valid = by_id[L1]
    assert valid.status == 'VALID' and valid.ndvi == pytest.approx(0.5) and valid.ndvi_min == valid.ndvi_max
    assert valid.red_reflectance == pytest.approx(0.08) and valid.nir_reflectance == pytest.approx(0.24)
    assert valid.window_pixels == 9 and valid.pixels['clear'] == 9 and valid.epsg == EPSG
    assert len(valid.data_sha256) == 64 and valid.tiles_read >= 3
