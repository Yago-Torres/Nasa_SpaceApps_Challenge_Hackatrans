@pytest.mark.asyncio
async def test_api_returns_observations_gaps_and_provenance(monkeypatch):
    files = {**scene_files(L1), **scene_files(S1, nir_band='B8A', fmask=CLOUDY)}
    fake = FakeNasa({'HLSL30': [granule_entry(L1)], 'HLSS30': [granule_entry(S1)]}, files)
    response = await api_get(PARAMS, fake, monkeypatch)
    assert response.status_code == 200, response.text
    body = response.json()
    assert body['kind'] == 'observation' and body['source_kind'] == 'OBSERVED'
    assert [o['status'] for o in body['observations']] == ['VALID', 'OBSCURED']
    assert body['observations'][0]['ndvi'] == pytest.approx(0.5) and body['observations'][1]['ndvi'] is None
    assert body['summary']['valid'] == 1 and body['summary']['gap_days'] == 29
    assert body['gaps'] == [{'start': '2023-06-01', 'end': '2023-06-02', 'days': 2},
                            {'start': '2023-06-04', 'end': '2023-06-30', 'days': 27}]
    prov = body['provenance']
    assert prov['provider'] == 'NASA LP DAAC' and prov['dataset_version'] == 'HLS v2.0'
    assert body['spatial_resolution'] == {'value': 30.0, 'unit': 'm', 'description': body['spatial_resolution']['description']}
    assert any('soil health' in item for item in body['limitations'])
    # the response checksum is deterministic for the same observations
    again = (await api_get(PARAMS, fake, monkeypatch)).json()
    assert again['provenance']['checksum_sha256'] == prov['checksum_sha256']


