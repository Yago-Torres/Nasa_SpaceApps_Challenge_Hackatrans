def _ifd_entry(bo, tag, typ, values, data_offset_holder):
    fmt = {3: 'H', 4: 'I', 12: 'd', 2: 's'}[typ]
    if typ == 2:
        raw = values.encode('latin-1') + b'\x00'
        count = len(raw)
    else:
        raw = struct.pack(bo + fmt * len(values), *values)
        count = len(values)
    return tag, typ, count, raw


def make_tiff(pixels: list[list[int]], *, bits=16, signed=True, tile=4, predictor=2, compression=8,
              big_endian=False, epsg=EPSG, nodata='-9999', origin=ORIGIN, pixel=30.0, extra_tags=(),
              drop_tags=()) -> bytes:
    """Build a tiled single-band GeoTIFF (classic TIFF) like an HLS COG, at a tiny size."""
    bo = '>' if big_endian else '<'
    height, width = len(pixels), len(pixels[0])
    code = {(8, False): 'B', (8, True): 'b', (16, False): 'H', (16, True): 'h'}[(bits, signed)]
    mask = (1 << bits) - 1
    across, down = -(-width // tile), -(-height // tile)
    tiles = []
    for ty in range(down):
        for tx in range(across):
            rows = []
            for r in range(tile):
                row = []
                for c in range(tile):
                    y, x = ty * tile + r, tx * tile + c
                    row.append(pixels[y][x] if y < height and x < width else 0)
                if predictor == 2:
                    row = [row[0]] + [(row[i] - row[i - 1]) & mask for i in range(1, tile)]
                    row = [v - (1 << bits) if signed and v >= 1 << (bits - 1) else v for v in row]
                rows.extend(row)
            raw = struct.pack(bo + code * len(rows), *rows)
            tiles.append(zlib.compress(raw) if compression == 8 else raw)
    geokeys = [1, 1, 0, 3, 1024, 0, 1, 1, 1025, 0, 1, 1, 3072, 0, 1, epsg]
    tags = [(256, 3, [width]), (257, 3, [height]), (258, 3, [bits]), (259, 3, [compression]), (262, 3, [1]),
            (277, 3, [1]), (284, 3, [1]), (317, 3, [predictor]), (322, 3, [tile]), (323, 3, [tile]),
            (324, 4, [0] * len(tiles)), (325, 4, [len(t) for t in tiles]), (339, 3, [2 if signed else 1]),
            (33550, 12, [pixel, pixel, 0.0]), (33922, 12, [0.0, 0.0, 0.0, origin[0], origin[1], 0.0]),
            (34735, 3, geokeys)]
    if nodata is not None:
        tags.append((42113, 2, nodata))
    tags = [t for t in tags if t[0] not in drop_tags] + list(extra_tags)
    tags.sort(key=lambda t: t[0])

    def build(tile_offsets):
        entries = [_ifd_entry(bo, tag, typ, tile_offsets if tag == 324 else vals, None) for tag, typ, vals in tags]
        ifd_size = 2 + 12 * len(entries) + 4
        data_start = 8 + ifd_size
        header = (b'MM' if big_endian else b'II') + struct.pack(bo + 'HI', 42, 8)
        ifd = struct.pack(bo + 'H', len(entries))
        blob = b''
        for tag, typ, count, raw in entries:
            if len(raw) <= 4:
                ifd += struct.pack(bo + 'HHI', tag, typ, count) + raw.ljust(4, b'\x00')
            else:
                ifd += struct.pack(bo + 'HHII', tag, typ, count, data_start + len(blob))
                blob += raw + (b'\x00' if len(raw) % 2 else b'')
        ifd += struct.pack(bo + 'I', 0)
        return header + ifd + blob

    head = build([0] * len(tiles))
    offsets, pos = [], len(head)
    for t in tiles:
        offsets.append(pos)
        pos += len(t)
    return build(offsets) + b''.join(tiles)


def utm_point(col: float, row: float) -> tuple[float, float]:
    """WGS 84 lat/lon of a raster position, found by bisection on latlon_to_utm (test helper)."""
    x, y = ORIGIN[0] + col * 30.0, ORIGIN[1] - row * 30.0
    lat, lon = 40.6, -4.17
    for _ in range(60):
        ex, ny = geotiff.latlon_to_utm(lat, lon, EPSG)
        lon += (x - ex) / 84_000
        lat += (y - ny) / 111_000
    return lat, lon


