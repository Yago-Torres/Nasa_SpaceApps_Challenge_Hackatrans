class FakeNasa:
    """CMR search + LP DAAC range reads. Records every request for assertions."""

    def __init__(self, entries: dict[str, list[dict]], files: dict[str, bytes], *, fail: dict[str, int] = None):
        self.entries, self.files, self.fail = entries, files, fail or {}
        self.requests: list[httpx.Request] = []

    def handler(self, request: httpx.Request) -> httpx.Response:
        self.requests.append(request)
        url = str(request.url)
        if request.url.host == 'cmr.earthdata.nasa.gov':
            product = request.url.params['short_name']
            return httpx.Response(200, json={'feed': {'entry': self.entries.get(product, [])}})
        for suffix, status in self.fail.items():
            if url.endswith(suffix):
                return httpx.Response(status)
        name = url.rsplit('/', 1)[-1]
        if request.url.host == hls.DATA_HOST:   # LP DAAC answers with a redirect to signed storage
            return httpx.Response(303, headers={'Location': f'https://signed.example/{name}'})
        data = self.files.get(name)
        if data is None:
            return httpx.Response(404)
        start, end = map(int, request.headers['Range'].removeprefix('bytes=').split('-'))
        return httpx.Response(206, content=data[start:end + 1])

    def client(self) -> httpx.AsyncClient:
        return httpx.AsyncClient(transport=httpx.MockTransport(self.handler), follow_redirects=True)


