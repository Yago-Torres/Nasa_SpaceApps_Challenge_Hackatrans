    assert cloudy.status == 'OBSCURED' and cloudy.ndvi is None and 'cloud' in cloudy.reason
    assert cloudy.pixels['cloud'] == 9 and cloudy.nir_band == 'B8A'
    skipped = by_id[L2]
    assert skipped.status == 'OBSCURED' and 'not read' in skipped.reason and skipped.tiles_read == 0
    assert hls.summary_counts(series) == {'acquisitions': 3, 'valid': 1, 'obscured': 2, 'no_data': 0, 'not_read': 0}
    assert hls.gaps(series) == [(date(2023, 6, 1), date(2023, 6, 2)), (date(2023, 6, 4), date(2023, 6, 30))]
    # the cloudy scene's red/NIR files were never requested
    assert not any(str(r.url).endswith(f'{S1}.B04.tif') for r in fake.requests)


