@pytest.mark.asyncio
async def test_api_without_token_is_503_and_rejected_token_is_502(monkeypatch):
    monkeypatch.delenv('EARTHDATA_TOKEN')
    response = await api_get(PARAMS)
    assert response.status_code == 503 and 'EARTHDATA_TOKEN' in response.json()['detail']
    monkeypatch.setenv('EARTHDATA_TOKEN', 'expired')
    fake = FakeNasa({'HLSL30': [granule_entry(L1)]}, scene_files(L1), fail={'.Fmask.tif': 401})
    response = await api_get(PARAMS, fake, monkeypatch)
    detail = response.json()['detail']
    assert response.status_code == 502 and 'token' in detail
    assert 'lpdaac' not in detail and str(round(LAT, 2)) not in detail
