def test_parse_header_and_decode_with_predictor_and_negative_values():
    grid = [[(r * 10 + c) * (-1 if (r + c) % 3 == 0 else 1) * 37 for c in range(6)] for r in range(6)]
    grid[0][0] = -9999
    data = make_tiff(grid)
    layout = geotiff.parse_header(data)
    assert (layout.width, layout.height, layout.tile_width, layout.tiles_across) == (6, 6, 4, 2)
    assert layout.epsg == EPSG and layout.nodata == -9999 and layout.predictor == 2 and layout.compression == 8
    assert (layout.origin_x, layout.origin_y, layout.pixel_size_x) == (*ORIGIN, 30.0)
    for r in range(6):
        for c in range(6):
            i = layout.tile_index(c, r)
            raw = data[layout.tile_offsets[i]: layout.tile_offsets[i] + layout.tile_byte_counts[i]]
            tile = geotiff.decode_tile(raw, layout)
            assert tile[(r % 4) * 4 + c % 4] == grid[r][c]


@pytest.mark.parametrize('big_endian', [False, True])
@pytest.mark.parametrize('bits,signed', [(8, False), (16, True), (16, False)])
@pytest.mark.parametrize('predictor,compression', [(1, 1), (2, 8), (1, 8)])
def test_decode_all_supported_sample_layouts(big_endian, bits, signed, predictor, compression):
    top = 255 if bits == 8 else (32767 if signed else 65535)
    low = -32768 if signed and bits == 16 else 0
    grid = [[low, top, 0, 1], [top, low, 1, 0], [5, 4, 3, 2], [low, low, top, top]]
    data = make_tiff(grid, bits=bits, signed=signed, predictor=predictor, compression=compression,
                     big_endian=big_endian, nodata=None)
    layout = geotiff.parse_header(data)
    raw = data[layout.tile_offsets[0]: layout.tile_offsets[0] + layout.tile_byte_counts[0]]
    tile = geotiff.decode_tile(raw, layout)
    assert [list(tile[i * 4:(i + 1) * 4]) for i in range(4)] == grid


def test_truncated_header_reports_the_size_needed():
    data = make_tiff([[1] * 4] * 4)
    with pytest.raises(geotiff.HeaderTruncated) as info:
        geotiff.parse_header(data[:40])
    assert info.value.required > 40
    assert geotiff.parse_header(data[:info.value.required + 200]).width == 4


