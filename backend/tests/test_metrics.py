from agroblackbox.services.metrics import summarize_power
from agroblackbox.services.report import build_report
from agroblackbox.services.rotations import rotation_examples


def test_monthly_anomalies_and_missing_values():
    observations={'PRECTOTCORR':{},'T2M_MAX':{}}
    for year in [2019,2020,2021,2022]:
        for day in [1,2,3]:
            date=f'{year}010{day}'
            observations['PRECTOTCORR'][date]=1.0 if year!=2022 else 0.0
            observations['T2M_MAX'][date]=20.0 if year!=2022 else 24.0
    out=summarize_power(observations,2022,2019,2021)
    assert out[0]['precipitation_anomaly_mm']==-3.0
    assert out[0]['max_temperature_anomaly_c']==4.0
    assert out[1]['precipitation_anomaly_mm'] is None


def test_rotations_ambiguous_impact_is_not_invented():
    examples=rotation_examples()
    assert len(examples)==3
    assert examples[0]['id']=='current'
    assert all(r['verified_impact'] is None for r in examples)


def test_report_is_marked_preliminary():
    report=build_report({'location_label':'Test', 'climate':{}})
    assert 'Preliminary autogenerated technical case investigation' in report
